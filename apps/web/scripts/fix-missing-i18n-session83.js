function main() {
  const report = JSON.parse(fs.readFileSync(REPORT, 'utf8'));
  const missing = (report.missingInId || []).map((x) => (typeof x === 'string' ? x : x.key));
  const idObj = loadLocale('id');
  const enObj = loadLocale('en');

  let applied = 0;
  const skipped = [];
  for (const key of missing) {
    const entry = T[key];
    if (!entry || typeof entry.id !== 'string' || typeof entry.en !== 'string') {
      skipped.push(key);
      continue;
    }
    setDeep(idObj, key, entry.id);
    setDeep(enObj, key, entry.en);
    applied++;
  }

  if (!DRY) {
    saveLocale('id', idObj);
    saveLocale('en', enObj);
  }
  // integrity re-parse
  JSON.parse(JSON.stringify(idObj));
  JSON.parse(JSON.stringify(enObj));

  console.log(`missing scanned : ${missing.length}`);
  console.log(`applied         : ${applied}`);
  console.log(`skipped (unauth): ${skipped.length}`);
  if (skipped.length) {
    require('fs').writeFileSync(path.resolve(__dirname, 'i18n-skipped-session83.json'), JSON.stringify(skipped, null, 2));
    console.log('skipped list → scripts/i18n-skipped-session83.json');
  }
  if (DRY) console.log('(dry-run: files NOT written)');
  else console.log('id.json + en.json updated.');
}

main();
